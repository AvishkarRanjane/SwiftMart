  if (catId === "gifting" || catId === "festive") return CATEGORY_DETAILS["festive-gifting"];
  if (catId === "grocery" || catId === "gourmet") return CATEGORY_DETAILS["grocery-gourmet"];
  if (catId === "auto" || catId === "car") return CATEGORY_DETAILS["automotive"];
  if (catId === "fitness" || catId === "sports") return CATEGORY_DETAILS["sports-fitness"];
  if (catId === "pets" || catId === "pet") return CATEGORY_DETAILS["pet-supplies"];
  if (catId === "garden" || catId === "outdoor") return CATEGORY_DETAILS["garden-outdoor"];
  if (catId === "decor" || catId === "lighting") return CATEGORY_DETAILS["home-decor"];
  if (catId === "kitchen" || catId === "home-kitchen" || catId === "dining") return CATEGORY_DETAILS["kitchen-dining"];
  if (catId === "tools" || catId === "hardware") return CATEGORY_DETAILS["home-improvement"];
  if (catId === "beauty" || catId === "health" || catId === "personal-care") return CATEGORY_DETAILS["health-beauty"];
